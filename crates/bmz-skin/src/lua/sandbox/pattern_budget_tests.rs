use super::*;

const CSV_SPLIT: &str = r#"
return function(csv)
    local count = 0
    for line in csv:gmatch('[^\n]+') do
        local s = line:gsub('\r', '')
        local values = {}
        local pattern = '%s*(.-)%s*,%s*'
        local function add(value) values[#values + 1] = value end
        s:gsub(pattern, add)
        add(s:gsub(pattern, ''))
        assert(#values == 9 and values[1] == '12')
        assert(values[9] == 'Synthetic title with spaces 0123456789')
        count = count + 1
    end
    return count
end
"#;

#[test]
fn csv_workload_fits_unchanged_load_budget_without_external_assets() {
    // ~79 KiB / 1178 rows, generated by BMZ rather than redistributed skin data.
    // The final field also exercises unsuccessful unanchored minimal matches.
    let csv = "12, 1749, 3, 4, 5, 6, 7, 8, Synthetic title with spaces 0123456789\r\n".repeat(1178);
    assert!((75_000..85_000).contains(&csv.len()));
    let stock = Lua::new();
    let reference: Function = stock.load(CSV_SPLIT).eval().unwrap();
    let start = Instant::now();
    let expected: usize = reference.call(csv.as_str()).unwrap();
    let stock_time = start.elapsed();
    let lua = Lua::new();
    let budget = install_instruction_limit(&lua).unwrap();
    let split: Function = lua.load(CSV_SPLIT).eval().unwrap();
    let start = Instant::now();
    assert_eq!(split.call::<usize>(csv.as_str()).unwrap(), expected);
    let metered_time = start.elapsed();
    assert_eq!(expected, 1178);
    let instructions = LUA_LOAD_INSTRUCTION_LIMIT - budget.total_remaining.load(Ordering::Relaxed);
    let work = LUA_LOAD_INSTRUCTION_LIMIT * PATTERN_WORK_PER_INSTRUCTION
        - budget.pattern_total_remaining.load(Ordering::Relaxed);
    // Deterministic regression gates; wall time is reported, not made flaky
    // by an absolute threshold on shared CI machines.
    assert!(instructions < 1_000_000, "CSV used {instructions} VM instructions");
    assert!(work < 32_000_000, "CSV used {work} native work units");
    eprintln!(
        "CSV {} bytes: stock={stock_time:?}, metered={metered_time:?}, instructions={instructions}, native work={work}",
        csv.len()
    );
}

#[test]
fn native_budget_covers_each_scanning_and_copying_path() {
    for source in [
        "string.find(string.rep('a', 20000), 'b', 1, true)",
        "string.find('x', string.rep('a', 20000))",
        "string.match('x', '['..string.rep('a', 20000)..']')",
        "string.match('x', '%f['..string.rep('a', 20000)..']')",
        "string.match('('..string.rep('a',20000)..')', '%b()')",
        "string.match(string.rep('a',20000), 'a+')",
        "string.match(string.rep('a',20000), '(a*)%1')",
        "string.gsub('a', 'a', string.rep('x',20000))",
        "string.gsub('a', 'a', function() return string.rep('x',20000) end)",
        "string.gsub('a', 'a', {a=string.rep('x',20000)})",
        "string.gsub(string.rep('a',20000), '', '%0')",
    ] {
        let lua = Lua::new();
        let budget = install_instruction_limit(&lua).unwrap();
        budget.pattern_total_remaining.store(4096, Ordering::Relaxed);
        let error = lua.load(source).exec().unwrap_err().to_string();
        assert!(error.contains("pattern work limit"), "{source}: {error}");
        assert!(budget.total_remaining.load(Ordering::Relaxed) > 0);
    }
}

#[test]
fn short_calls_errors_and_iterators_share_the_native_quota() {
    for source in [
        "for i=1,100 do string.find('a','a') end",
        "for i=1,100 do pcall(string.match, 'a', '[') end",
        "local next=string.gmatch(string.rep('a',100), '.'); for i=1,100 do next() end",
        "for i=1,100 do coroutine.wrap(function() return string.find('a','a') end)() end",
        "while true do pcall(function() string.find(string.rep('a',20000), 'b',1,true) end) end",
        "while true do xpcall(function() error('x') end, function() string.find(string.rep('a',20000), 'b',1,true) end) end",
    ] {
        let lua = Lua::new();
        let budget = install_instruction_limit(&lua).unwrap();
        budget.pattern_total_remaining.store(8192, Ordering::Relaxed);
        let error = lua.load(source).exec().unwrap_err().to_string();
        assert!(error.contains("pattern work limit"), "{source}: {error}");
        assert!(budget.total_remaining.load(Ordering::Relaxed) > 0);
    }
}

#[test]
fn native_quota_resets_only_at_the_correct_runtime_boundaries() {
    let lua = Lua::new();
    let budget = install_instruction_limit(&lua).unwrap();
    budget.begin_runtime_callback(true);
    lua.load("next_match = string.gmatch(string.rep('a',100), '.')").exec().unwrap();
    budget.pattern_total_remaining.store(1500, Ordering::Relaxed);
    lua.load("assert(next_match() == 'a')").exec().unwrap();
    // A fresh callback gets its own allowance, but cannot reset this frame.
    budget.begin_runtime_callback(false);
    assert!(
        lua.load("next_match()").exec().unwrap_err().to_string().contains("pattern work limit")
    );
    budget.begin_runtime_callback(true);
    lua.load("assert(next_match() == 'a')").exec().unwrap();
    // Conversely, an individual callback limit cannot be bypassed by having
    // abundant frame work left. The next callback restores only that limit.
    budget.pattern_callback_remaining.store(1, Ordering::Relaxed);
    assert!(
        lua.load("next_match()").exec().unwrap_err().to_string().contains("pattern work limit")
    );
    let remaining = budget.pattern_total_remaining.load(Ordering::Relaxed);
    budget.begin_runtime_callback(false);
    lua.load("assert(next_match() == 'a')").exec().unwrap();
    assert!(budget.pattern_total_remaining.load(Ordering::Relaxed) < remaining);
    budget.pattern_total_remaining.store(0, Ordering::Relaxed);
    budget.begin_inference();
    lua.load("assert(next_match() == 'a')").exec().unwrap();

    lua.load("long_match = string.gmatch(string.rep('a',5000), 'a+')").exec().unwrap();
    budget.pattern_total_remaining.store(4096, Ordering::Relaxed);
    assert!(
        lua.load("long_match()").exec().unwrap_err().to_string().contains("pattern work limit")
    );
    budget.begin_runtime_callback(true);
    lua.load("assert(#long_match() == 5000)").exec().unwrap();
}

#[test]
#[ignore = "manual timing of the pinned mz-select CSV when its submodule is present"]
fn benchmark_mz_select_csv() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../data/skins/mz-select/list.csv");
    let csv = fs::read_to_string(path).expect("initialize mz-select submodule");
    let script = CSV_SPLIT
        .replace("assert(#values == 9 and values[1] == '12')", "")
        .replace("assert(values[9] == 'Synthetic title with spaces 0123456789')", "");
    let stock = Lua::new();
    let stock_run: Function = stock.load(&script).eval().unwrap();
    let lua = Lua::new();
    let budget = install_instruction_limit(&lua).unwrap();
    let metered_run: Function = lua.load(&script).eval().unwrap();
    let start = Instant::now();
    let expected: usize = stock_run.call(csv.as_str()).unwrap();
    let stock_time = start.elapsed();
    let start = Instant::now();
    assert_eq!(metered_run.call::<usize>(csv.as_str()).unwrap(), expected);
    eprintln!(
        "mz-select CSV {} bytes / {expected} rows: stock={stock_time:?}, metered={:?}, VM instructions={}, native work={}",
        csv.len(),
        start.elapsed(),
        LUA_LOAD_INSTRUCTION_LIMIT - budget.total_remaining.load(Ordering::Relaxed),
        LUA_LOAD_INSTRUCTION_LIMIT * PATTERN_WORK_PER_INSTRUCTION
            - budget.pattern_total_remaining.load(Ordering::Relaxed)
    );
}
